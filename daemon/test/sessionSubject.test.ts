import { describe, expect, it } from "vitest";
import { presentablePrompt, sessionSubject } from "../src/sessionSubject.js";

describe("session subjects", () => {
  it("prefers the native title and keeps ordinary requests", () => {
    expect(sessionSubject({ title: "Fix login crash", summary: "please fix it" })).toBe("Fix login crash");
    expect(sessionSubject({ summary: "Add a dark mode toggle to settings" })).toBe("Add a dark mode toggle to settings");
  });

  it("takes the request out of Codex attachment preambles", () => {
    const prompt = "# Files mentioned by the user:\n\n## Photo 1.jpg: /tmp/codex-remote-attachments/01a1/Photo 1.jpg\n\n## My request for Codex:\nMake the bat swing faster";
    expect(presentablePrompt(prompt)).toBe("Make the bat swing faster");
    expect(presentablePrompt("# Files mentioned by the user:\n\n## Photo 1.jpg: /tmp/codex-remote-attachments/01a1/Photo")).toBeNull();
  });

  it("drops tool boilerplate and never shows local paths", () => {
    for (const boilerplate of [
      "This session is being continued from a previous conversation that ran out of context. The conversation is summarized below:",
      "Caveat: The messages below were generated by the user while running local commands.",
      "[Request interrupted by user]",
      "<command-name>/clear</command-name>",
    ]) {
      expect(sessionSubject({ summary: boilerplate }), boilerplate).toBeNull();
    }
    expect(presentablePrompt("Read /Users/someone/project/secrets.txt and ~/notes.md please")).toBe("Read and please");
    expect(sessionSubject({ title: "This session is being continued from a previous conversation", summary: "Ship it" })).toBe("Ship it");
  });
});
