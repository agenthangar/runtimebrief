/**
 * A session's subject as people should read it: the native title when there
 * is one, otherwise the request, without tool boilerplate or local paths.
 * Returns null when nothing presentable remains.
 */
export function sessionSubject(session: { title?: string | undefined; summary?: string | undefined }): string | null {
  return describedSubject(session)?.text ?? null;
}

/** Where a subject came from: a native session title is safe to show in a
 * presentation; a request is the person's own words and may not be. */
export type SubjectSource = "title" | "request";

export function describedSubject(
  session: { title?: string | undefined; summary?: string | undefined },
): { text: string; source: SubjectSource } | null {
  const title = presentablePrompt(session.title);
  if (title) return { text: title, source: "title" };
  const request = presentablePrompt(session.summary);
  return request ? { text: request, source: "request" } : null;
}

const BOILERPLATE = [
  // RuntimeBrief's own launch names: "RuntimeBrief Meal Planner 21bfbe3a".
  /^RuntimeBrief\b.*\b[0-9a-f]{8}(?:-[0-9a-f-]+)?$/i,
  /^this session is being continued from a previous conversation/i,
  /^caveat: the messages below were generated by the user/i,
  /^\[request interrupted/i,
  /^<[a-z-]+>/i,
];

export function presentablePrompt(text: string | undefined | null): string | null {
  if (!text) return null;
  let value = text;
  // Codex remote prompts list attachments before the request itself.
  const request = /#+\s*My request for Codex:\s*([\s\S]*)$/i.exec(value);
  if (request) value = request[1]!;
  else if (/^\s*#\s*Files mentioned by the user/i.test(value)) return null;
  value = value
    .replace(/(?:^|\s)(?:~|\/(?:Users|tmp|private|var|home|Volumes))\/\S+/g, " ")
    .replace(/^\s*#+\s*/gm, "")
    .replace(/\s+/g, " ")
    .trim();
  if (!value || BOILERPLATE.some((pattern) => pattern.test(value))) return null;
  return value;
}
